    private void btn_cadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_cadastrarActionPerformed
      //logica da modalidade
      if(rdo_presencial.isSelected()){
          modalidade = "Presencial";
      }
      if(rdo_online.isSelected()){
          modalidade = "Online";
      }  
      // logica da situacao
      if(rdo_cancelado.isSelected()){
          situacao = "Cancelado";
      }
      if(rdo_agendado.isSelected()){
          situacao = "Agendado";
      }
      if(rdo_realizado.isSelected()){
          situacao = "Realizado";
      }
      String tipo = cmb_tipo.getSelectedItem()+"";
      Evento e = new Evento(
       txt_nome_evento.getText(),
       txt_data.getText(),
       txt_local.getText(),
      (String)cmb_tipo.getSelectedItem(),
       modalidade,
       situacao
      );
      if(linhaEdicao == -1){
            listaEventos.add(e);
        }else{
            listaEventos.set(linhaEdicao, e);
            linhaEdicao = -1;
        }
        arquivo.gravaArquivo();
        carregarTabela();
        JOptionPane.showMessageDialog(null, "Dados do Evento Salvos com sucesso!");
        System.out.println("Evento add");
        for(Evento evento : listaEventos){
            System.out.println(evento);
        }
        carregarTabela();
        txt_nome_evento.setText("");
        txt_data.setText("");
        txt_local.setText("");
        btn_grp_situacao.clearSelection();
        btn_grp_modalidade.clearSelection();
        cmb_tipo.setSelectedIndex(0);
      
    }//GEN-LAST:event_btn_cadastrarActionPerformed

