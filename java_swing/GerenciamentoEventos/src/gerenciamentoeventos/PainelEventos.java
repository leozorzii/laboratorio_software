    private void btn_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_editarActionPerformed
       int linha = tbl_eventos.getSelectedRow();
       if(linha == -1){
            JOptionPane.showMessageDialog(null, "Selecione um evento para editar!");
            return;
       }
       linhaEdicao = linha;
       Evento e = listaEventos.get(linha);
       txt_nome_evento.setText(e.nomeEvento);
       txt_data.setText(e.data+"");
       txt_local.setText(e.local+"");
       //modalidade
       if(e.modalidade.equalsIgnoreCase(modalidade)){
           rdo_presencial.setSelected(true);
       }
       if(e.modalidade.equalsIgnoreCase(modalidade)){
           rdo_online.setSelected(true);
       }
       
        //situacao
       if(e.situacao.equalsIgnoreCase(situacao)){
           rdo_agendado.setSelected(true);
       }
       if(e.situacao.equalsIgnoreCase(situacao)){
           rdo_realizado.setSelected(true);
       }
       if(e.situacao.equalsIgnoreCase(situacao)){
           rdo_cancelado.setSelected(true);
       }
       cmb_tipo.setSelectedItem(e.tipo);
    }//GEN-LAST:event_btn_editarActionPerformed

