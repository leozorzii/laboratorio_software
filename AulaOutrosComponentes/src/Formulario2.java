    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if(rdoMasculino.isSelected()){
           // JOptionPane.showMessageDialog(null, txtNome.getText()+" - Sexo Masculino",
                  //  "Alerta", JOptionPane.OK_OPTION);
            sexo = 'M';
        }
        else if(rdoFeminino.isSelected()){
           // JOptionPane.showMessageDialog(null, txtNome.getText()+" - Sexo Feminino", 
             //       "Alerta", JOptionPane.OK_OPTION);
            sexo = 'F';
        }
        else{
            JOptionPane.showMessageDialog(null, "Selecione um sexo", "Erro", JOptionPane.ERROR_MESSAGE);
        }
        
        tecnologia = chk_Tecnologia.isSelected();
        astronomia = chk_Astronomia.isSelected();
        esportes = chk_Esportes.isSelected();

        String idioma = cmb_Idioma.getSelectedItem()+"";
        Pessoa p = new Pessoa (txtNome.getText(), sexo, (String)cmb_Idioma.getSelectedItem());
        if(linhaEdicao == -1){
            listaPessoas.add(p);
        }else{
            listaPessoas.set(linhaEdicao, p);
            linhaEdicao = -1;
        }
        
        arquivo.gravaArquivo();
        carregarTabela();
        JOptionPane.showMessageDialog(
                null,
                "Dados Salvos com sucesso"
        );
        System.out.println("Pessoa add");
        for(Pessoa pessoa : listaPessoas){
            System.out.println(pessoa);
        }
        
        carregarTabela();
        txtNome.setText("");
        btnGrpSexo.clearSelection();
        chk_Tecnologia.setSelected(false);
        chk_Astronomia.setSelected(false);
        chk_Esportes.setSelected(false);
        cmb_Idioma.setSelectedIndex(0);
    }//GEN-LAST:event_btnSalvarActionPerformed

