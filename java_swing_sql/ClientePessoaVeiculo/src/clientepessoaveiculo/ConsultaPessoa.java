    private void btn_consultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_consultarActionPerformed
     try{
         String host = "localhost";
     int porta = 12345;
     
     Socket clienteSocket = new Socket(host, porta);
        System.out.println("Conexão efetuada com sucesso");
        
        ObjectOutputStream out = new ObjectOutputStream(clienteSocket.getOutputStream());
        ObjectInputStream in = new ObjectInputStream(clienteSocket.getInputStream());
        int id = Integer.parseInt(txt_codigo.getText());
        out.writeInt(id);
        out.flush();
        Pessoa p = (Pessoa) in.readObject();
         System.out.println("Resposta: " + p.getNome());
         lbl_nome2.setText(p.getNome());
         lbl_sexo2.setText(p.getSexo());
         jLabel6.setText(p.getIdioma());
         
         out.close();
         in.close();
         clienteSocket.close();
        }catch(IOException ex){
            System.out.println("Erro na comunicacao com o servidor");
        }catch(ClassNotFoundException ex){
            System.out.println("Classe Pessoa não encontrada");
        }
    }//GEN-LAST:event_btn_consultarActionPerformed

