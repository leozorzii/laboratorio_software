    private void carregarTabela(String nome, String categoria){
        ProdutoDAO pDAO = new ProdutoDAO();
        List<Produto> lista = pDAO.getProdutos(nome, categoria);

        DefaultTableModel tabela = (DefaultTableModel) tbl_produtos.getModel();
        tabela.setRowCount(0); // limpa a tabela antes de preencher
        for(Produto p : lista){
            Object[] obj = {
                p.getId(),
                p.getNome(),
                String.format("%.2f", p.getPreco()),
                p.getQuantidade(),
                p.getCategoria().getNome()
            };
            tabela.addRow(obj);
        }
    }

