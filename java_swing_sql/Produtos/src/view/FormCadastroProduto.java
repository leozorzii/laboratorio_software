    // busca as categorias no banco e joga no combo (objetos Categoria, nao Strings)
    public void preencherComboCategorias(){
        CategoriaDAO cDAO = new CategoriaDAO();
        List<Categoria> lista = cDAO.getCategorias();
        cmb_categorias.removeAllItems(); // limpa antes de preencher
        for(Categoria c : lista){
            cmb_categorias.addItem(c);
        }
    }

    private void limparFormulario(){
        txt_nome.setText("");
        txt_preco.setText("");
        txt_quantidade.setText("");
        if(cmb_categorias.getItemCount() > 0){
            cmb_categorias.setSelectedIndex(0);
        }
        txt_nome.requestFocus();
    }

