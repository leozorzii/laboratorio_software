    private void btn_salvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_salvarActionPerformed
        Categoria cat = (Categoria) cmb_categorias.getSelectedItem();
        if(cat == null){
            JOptionPane.showMessageDialog(this, "Cadastre uma categoria antes");
            return;
        }
        if(txt_nome.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Informe o nome do produto");
            return;
        }
        Produto p = new Produto();
        p.setNome(txt_nome.getText().trim());
        try{
            // aceita 10,50 e 10.50
            p.setPreco(Double.parseDouble(txt_preco.getText().trim().replace(",", ".")));
            p.setQuantidade(Integer.parseInt(txt_quantidade.getText().trim()));
        }catch(NumberFormatException ex){
            JOptionPane.showMessageDialog(this, "Preco e quantidade devem ser numeros");
            return;
        }
        p.setCategoria(cat);

        ProdutoDAO pDAO = new ProdutoDAO();
        pDAO.inserir(p);
        JOptionPane.showMessageDialog(this, "Produto cadastrado");
        limparFormulario();
    }//GEN-LAST:event_btn_salvarActionPerformed

