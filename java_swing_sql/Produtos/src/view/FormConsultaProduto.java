    private void btn_consultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_consultarActionPerformed
        int id;
        try{
            id = Integer.parseInt(txt_id.getText().trim());
        }catch(NumberFormatException ex){
            JOptionPane.showMessageDialog(this, "Digite um ID numerico");
            return;
        }
        ProdutoDAO pDAO = new ProdutoDAO();
        Produto p = pDAO.getProduto(id);
        if(p == null){
            limparFormulario();
            JOptionPane.showMessageDialog(this, "Produto nao encontrado");
        }else{
            txt_id2.setText(p.getId() + "");
            txt_nome.setText(p.getNome());
            txt_preco.setText(p.getPreco() + "");
            txt_quantidade.setText(p.getQuantidade() + "");
            // seleciona no combo a categoria do produto (funciona por causa do equals do Bean)
            cmb_categorias.setSelectedItem(p.getCategoria());
        }
    }//GEN-LAST:event_btn_consultarActionPerformed

    private void btn_atualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_atualizarActionPerformed
        if(txt_id2.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Consulte um produto primeiro");
            return;
        }
        Categoria cat = (Categoria) cmb_categorias.getSelectedItem();
        Produto p = new Produto();
        p.setId(Integer.parseInt(txt_id2.getText()));
        p.setNome(txt_nome.getText().trim());
        try{
            p.setPreco(Double.parseDouble(txt_preco.getText().trim().replace(",", ".")));
            p.setQuantidade(Integer.parseInt(txt_quantidade.getText().trim()));
        }catch(NumberFormatException ex){
            JOptionPane.showMessageDialog(this, "Preco e quantidade devem ser numeros");
            return;
        }
        p.setCategoria(cat); // categoria escolhida no combo (pode ter sido trocada)

        ProdutoDAO pDAO = new ProdutoDAO();
        pDAO.editar(p);
        JOptionPane.showMessageDialog(this, "Produto atualizado");
        limparFormulario();
    }//GEN-LAST:event_btn_atualizarActionPerformed

    private void btn_excluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_excluirActionPerformed
        if(txt_id2.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Consulte um produto primeiro");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir esse registro?", "Exclusao", JOptionPane.YES_NO_OPTION);
        if(resposta == JOptionPane.YES_OPTION){
            ProdutoDAO pDAO = new ProdutoDAO();
            pDAO.excluir(Integer.parseInt(txt_id2.getText()));
            limparFormulario();
        }
    }//GEN-LAST:event_btn_excluirActionPerformed

