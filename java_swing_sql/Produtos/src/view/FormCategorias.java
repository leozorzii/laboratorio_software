    private void btn_excluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_excluirActionPerformed
        if(txt_id.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Selecione uma categoria na tabela");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir essa categoria?", "Exclusao", JOptionPane.YES_NO_OPTION);
        if(resposta == JOptionPane.YES_OPTION){
            CategoriaDAO cDAO = new CategoriaDAO();
            if(cDAO.excluir(Integer.parseInt(txt_id.getText()))){
                carregarTabela();
                limparFormulario();
            }else{
                JOptionPane.showMessageDialog(this, "Nao foi possivel excluir: existem produtos nessa categoria");
            }
        }
    }//GEN-LAST:event_btn_excluirActionPerformed

    private void tbl_categoriasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbl_categoriasMouseClicked
        // linha clicada -> campos (modo edicao)
        int linha = tbl_categorias.getSelectedRow();
        if(linha >= 0){
            txt_id.setText(tbl_categorias.getValueAt(linha, 0).toString());
            txt_nome.setText(tbl_categorias.getValueAt(linha, 1).toString());
        }
    }//GEN-LAST:event_tbl_categoriasMouseClicked

